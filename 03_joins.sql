-- JOINS
-- Display: customer_name, order_id, order_date, total_amount.

SELECT c.customer_name,o.order_id,o.order_date,o.total_amount 
FROM customers c
INNER JOIN orders o
ON c.customer_id = o.customer_id;

-- Q22. Display: order_id, product_name, quantity, unit_price

SELECT o.order_id,p.product_name,
       oi.quantity,oi.unit_price
FROM orders o
INNER JOIN order_items oi
ON o.order_id = oi.order_id
INNER JOIN products p
ON oi.product_id = p.product_id;

-- Find all customers who have never placed an order.

SELECT c.customer_id,c.customer_name 
FROM customers c
LEFT JOIN orders o
ON c.customer_id = o.customer_id
WHERE o.order_id IS NULL;

-- Display customer name, order ID, payment method and payment status.

SELECT c.customer_name,o.order_id,
	    p.payment_method,p.payment_status
 FROM customers c
 INNER JOIN orders o
 ON c.customer_id = o.customer_id
 INNER JOIN payments p
 ON o.order_id = p.order_id;
 
 -- Display: customer, order, product, quantity, payment.
 
 SELECT c.customer_name AS customer,
         o.order_id AS orders,
         p.product_name AS products,
         oi.quantity AS quantity,
         py.payment_status AS payment
 FROM customers c
 LEFT JOIN orders o
 ON c.customer_id = o.customer_id
 LEFT JOIN order_items oi
 ON o.order_id = oi.order_id
 LEFT JOIN products p
 ON oi.product_id = p.product_id
 LEFT JOIN payments py
 ON o.order_id = py.order_id;
 
 -- Find total spending by each customer.
 
SELECT
    c.customer_id,
    c.customer_name,
    SUM(o.total_amount) AS total_spending
FROM customers c
INNER JOIN orders o
    ON c.customer_id = o.customer_id
WHERE o.order_status NOT IN ('Cancelled', 'Returned')
GROUP BY c.customer_id, c.customer_name
ORDER BY total_spending DESC;
 
-- Find total quantity sold for each product.

SELECT
    p.product_id,
    p.product_name,
    SUM(oi.quantity) AS total_quantity
FROM products p
INNER JOIN order_items oi
    ON p.product_id = oi.product_id
INNER JOIN orders o
    ON oi.order_id = o.order_id
WHERE o.order_status NOT IN ('Cancelled', 'Returned')
GROUP BY p.product_id, p.product_name
ORDER BY total_quantity DESC;

-- Find the most purchased product.

WITH product_units AS (
    SELECT
        p.product_id,
        p.product_name,
        SUM(oi.quantity) AS units_sold
    FROM products p
    INNER JOIN order_items oi
        ON p.product_id = oi.product_id
    INNER JOIN orders o
        ON oi.order_id = o.order_id
    WHERE o.order_status NOT IN ('Cancelled', 'Returned')
    GROUP BY p.product_id, p.product_name
),
ranked_products AS (
    SELECT
        product_id,
        product_name,
        units_sold,
        DENSE_RANK() OVER (ORDER BY units_sold DESC) AS sales_rank
    FROM product_units
)
SELECT product_id, product_name, units_sold, sales_rank
FROM ranked_products
WHERE sales_rank = 1
ORDER BY product_id; 

-- Find revenue generated by each product category.

SELECT
    p.category,
    SUM(oi.quantity * oi.unit_price) AS total_revenue
FROM products p
INNER JOIN order_items oi
    ON p.product_id = oi.product_id
INNER JOIN orders o
    ON oi.order_id = o.order_id
WHERE o.order_status NOT IN ('Cancelled', 'Returned')
GROUP BY p.category
ORDER BY total_revenue DESC;

-- Find customers who purchased Electronics products.

SELECT DISTINCT
    c.customer_id,
    c.customer_name
FROM customers c
INNER JOIN orders o
    ON c.customer_id = o.customer_id
INNER JOIN order_items oi
    ON o.order_id = oi.order_id
INNER JOIN products p
    ON oi.product_id = p.product_id
WHERE p.category = 'Electronics';
